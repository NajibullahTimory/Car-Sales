// زبان انتخاب‌شده را روی سند ثبت می‌کند تا جهت و فونت همهٔ صفحه‌ها عوض شود.
function syncDocumentLanguage(language) {
  const currentLanguage = (language || 'en').split('-')[0];
  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = ['fa', 'ps'].includes(currentLanguage) ? 'rtl' : 'ltr';
  localStorage.setItem('motrly_language', currentLanguage);
}

i18n.on('languageChanged', syncDocumentLanguage);
syncDocumentLanguage(i18n.resolvedLanguage || i18n.language || 'en');

